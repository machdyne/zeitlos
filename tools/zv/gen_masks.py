#!/usr/bin/env python3
#
# gen_masks.py -- the dither threshold masks used by ZV (docs/zv.md).
#
# Writes sw/common/zv_masks.h:
#
#   zv_mask_bayer8[64]   the classic 8x8 ordered (Bayer) matrix
#   zv_mask_vac8[64]     an 8x8 void-and-cluster tile (blue-noise-like)
#   zv_mask_bn64[4096]   a 64x64 void-and-cluster mask, for the Linux
#                        player's "free dither" preview only
#
# Every mask holds ranks: an 8x8 one 0..63 once each, the 64x64 one
# 0..4095 once each. A pixel of linear brightness L (0..1) is white when
# L > (rank + 0.5) / N.
#
# Void-and-cluster is R. Ulichney's method (1993); its patent has long
# expired. numpy is needed to run this script, not to build anything:
# the generated header is checked in.
#
#   python3 tools/zv/gen_masks.py

import os
import sys

import numpy as np


def bayer(n):
	m = np.array([[0, 2], [3, 1]])
	while m.shape[0] < n:
		m = np.block([[4 * m, 4 * m + 2], [4 * m + 3, 4 * m + 1]])
	return m


def vac(n, sigma=1.5, seed=1):
	rng = np.random.default_rng(seed)
	# toroidal gaussian, applied by FFT
	ax = np.arange(n)
	d = np.minimum(ax, n - ax)
	g = np.exp(-(d[:, None] ** 2 + d[None, :] ** 2) / (2 * sigma * sigma))
	G = np.fft.fft2(g)

	def energy(b):
		return np.real(np.fft.ifft2(np.fft.fft2(b) * G))

	def tightest(b):
		e = energy(b)
		e[b == 0] = -1e9
		return np.unravel_index(np.argmax(e), b.shape)

	def largest_void(b):
		e = energy(b)
		e[b == 1] = 1e9
		return np.unravel_index(np.argmin(e), b.shape)

	total = n * n
	ones = max(1, total // 10)
	b = np.zeros((n, n), dtype=np.int64)
	idx = rng.choice(total, ones, replace=False)
	b.flat[idx] = 1
	# initial binary pattern: relax until the tightest cluster is the
	# largest void
	for _ in range(total * 4):
		c = tightest(b)
		b[c] = 0
		v = largest_void(b)
		if v == c:
			b[c] = 1
			break
		b[v] = 1
	rank = np.zeros((n, n), dtype=np.int64)
	# phase 1: ranks below the initial pattern
	p = b.copy()
	r = int(p.sum()) - 1
	while r >= 0:
		c = tightest(p)
		p[c] = 0
		rank[c] = r
		r -= 1
	# phase 2: up to half
	p = b.copy()
	r = int(p.sum())
	while r < total // 2:
		v = largest_void(p)
		p[v] = 1
		rank[v] = r
		r += 1
	# phase 3: the rest, by the minority pixels (now the zeros)
	q = 1 - p
	while r < total:
		c = tightest(q)
		q[c] = 0
		rank[c] = r
		r += 1
	assert sorted(rank.flat) == list(range(total))
	return rank


def emit(f, name, m):
	flat = [int(x) for x in m.flat]
	ctype = "uint8_t" if max(flat) < 256 else "uint16_t"
	f.write("static const %s %s[%d] = {\n" % (ctype, name, len(flat)))
	w = m.shape[1]
	for i in range(0, len(flat), w):
		row = flat[i:i + w]
		for j in range(0, len(row), 16):
			f.write("\t" + ", ".join("%d" % x for x in row[j:j + 16]) + ",\n")
	f.write("};\n\n")


def main():
	root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
	out = os.path.join(root, "sw", "common", "zv_masks.h")
	b8 = bayer(8)
	v8 = vac(8, sigma=1.5)
	v64 = vac(64, sigma=1.5)
	with open(out, "w") as f:
		f.write("// Generated by tools/zv/gen_masks.py -- do not edit.\n")
		f.write("// Dither threshold ranks for ZV (docs/zv.md, \"Dithering\").\n\n")
		f.write("#ifndef ZV_MASKS_H\n#define ZV_MASKS_H\n\n#include <stdint.h>\n\n")
		emit(f, "zv_mask_bayer8", b8)
		emit(f, "zv_mask_vac8", v8)
		f.write("#ifdef ZV_WANT_BN64\n")
		emit(f, "zv_mask_bn64", v64)
		f.write("#endif\n\n#endif\n")
	print("wrote", out)


if __name__ == "__main__":
	sys.exit(main())
