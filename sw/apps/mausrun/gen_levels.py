#!/usr/bin/env python3
#
# Zeitlos mausrun -- the levels, compiled in.
#
# Emits levels_builtin.c from sw/data/mausrun/levels/NN.txt, so the game
# has all its levels even on a card without /data/mausrun/levels (a
# card from before the update plan copied them, or the app copied over
# by hand). The files still win: a level file on the card replaces the
# compiled-in level of its number, and levels past the last compiled-in
# one come from files alone (docs/mausrun.md, "Levels").
#
#   python3 gen_levels.py
#
# Comments (# lines before `map`) are left out: they are for whoever
# reads the file, and cost the binary nothing that way. The generated
# file is committed, as sprites.c is; tests/levelcheck.c checks that it
# says what the files say, so an edited level not regenerated fails the
# build's tests rather than shipping two different level 3s.

import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "data", "mausrun", "levels")
OUT = os.path.join(HERE, "levels_builtin.c")


def c_lines(path):
    text = open(path).read()
    head, sep, body = text.partition("map\n")
    if not sep:
        sys.exit("%s: no map line" % path)
    lines = [l for l in head.splitlines() if l.strip() and not l.startswith("#")]
    lines.append("map")
    lines += body.splitlines()
    for l in lines:
        if '"' in l or "\\" in l:
            sys.exit("%s: a quote or backslash in a level" % path)
    return lines


def main():
    files = sorted(glob.glob(os.path.join(SRC, "[0-9][0-9].txt")))
    for i, f in enumerate(files):
        if os.path.basename(f) != "%02d.txt" % (i + 1):
            sys.exit("levels must be 01.txt, 02.txt, ... with none missing: %s" % f)
    with open(OUT, "w") as o:
        o.write("/* GENERATED by gen_levels.py from sw/data/mausrun/levels -- do not\n"
                " * edit. Edit the level files and re-run it. */\n\n"
                "#include \"level.h\"\n\n")
        for i, f in enumerate(files):
            o.write("static const char lv%02d[] =\n" % (i + 1))
            o.write("\n".join('\t"%s\\n"' % l for l in c_lines(f)))
            o.write(";\n\n")
        o.write("const char *const mr_builtin_levels[] = {\n")
        for i in range(len(files)):
            o.write("\tlv%02d,\n" % (i + 1))
        o.write("};\n\nconst int mr_builtin_count = %d;\n" % len(files))
    print("wrote %s: %d levels" % (OUT, len(files)))


main()
