int mj_layout_builtin_count(void)
{
	return (int)(sizeof(builtin) / sizeof(builtin[0]));
}

const char *mj_layout_builtin_text(int i)
{
	if (i < 0 || i >= mj_layout_builtin_count()) return 0;
	return builtin[i];
}
