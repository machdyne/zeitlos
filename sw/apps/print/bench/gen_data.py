#!/usr/bin/env python3
"""Writes benchdata.c: a job (made by sw/apps/slide's `make job`), the
fonts it names and the pictures it shows, as C arrays with their card
paths, so the benchmark needs no filesystem under the simulator."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, "..", "..", "..", "..")
job = sys.argv[2] if len(sys.argv) > 2 else "/tmp/slide/deck.zpp"
files = [("/tmp/job.zpp", job)]
for f in sorted(os.listdir(os.path.join(root, "sw/data/font/zhf"))):
    files.append(("/sys/fonts/" + f, os.path.join(root, "sw/data/font/zhf", f)))
for f in ("m9x15.zfn", "m6x13.zfn"):
    files.append(("/sys/fonts/" + f, os.path.join(root, "sw/data/font/zfn", f)))
files.append(("/media/images/squirrel.jpg", os.path.join(root, "sw/data/images/squirrel.jpg")))
out = ["/* generated by gen_data.py -- do not edit */", "#include <stdint.h>",
       "typedef struct { const char *path; const uint8_t *data; uint32_t len; } bench_file_t;"]
for i, (_, p) in enumerate(files):
    b = open(p, "rb").read()
    out.append("static const uint8_t d%d[%d] = {" % (i, len(b)))
    for k in range(0, len(b), 24):
        out.append("\t" + ",".join(str(x) for x in b[k:k + 24]) + ",")
    out.append("};")
out.append("const bench_file_t bench_files[] = {")
for i, (path, p) in enumerate(files):
    out.append('\t{ "%s", d%d, %d },' % (path, i, os.path.getsize(p)))
out.append("\t{ 0, 0, 0 },\n};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
