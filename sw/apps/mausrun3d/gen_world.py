#!/usr/bin/env python3
"""
mausrun3d -- a world made from one of mausrun's levels (docs/mausrun3d.md).

    python3 gen_world.py ../../data/mausrun/levels/01.txt > ../../data/mausrun3d/world01.txt
    python3 gen_world.py --size 512 ...

The old level is a side view, 15 rows by up to 512 columns. Its run is
laid out as a path five tiles wide winding across an island: every old
column a step along the path, its floor the path's height, its pits
chasms across the path, its boxes, shelves, springs, ? boxes, cheese,
foes, mouse holes, star and cheese wheel where they were along the run,
on the path's middle. Around the path: meadow with low plateaus, a
beach, the sea. Deterministic: the same level gives the same world.

The world file (docs/mausrun3d.md, "Worlds"): a header, then three
layers of SIZE rows of SIZE characters, top-down, x across, z down --

    ground   the ground's top, in blocks: 0-9, a-f (10-15); '.' none (a chasm)
    surface  what the top is: g grass, p path, s sand, r rock, d earth
    water    the water's surface, in blocks, where there is water: 0-9, a-f; '.' none

-- then the blocks and things, one a line: `x z y c`.
"""

import math
import sys

HMAX = 15


def parse_level(path):
    meta, rows, in_map = {}, [], False
    for line in open(path):
        line = line.rstrip('\n')
        if in_map:
            rows.append(line)
            continue
        s = line.strip()
        if not s or s.startswith('#'):
            continue
        if s == 'map':
            in_map = True
            continue
        k, _, v = s.partition(' ')
        meta[k] = v.strip()
    w = max(len(r) for r in rows)
    rows = [r.ljust(w, '.') for r in rows]
    return meta, rows


def hash2(x, z, seed):
    h = (x * 374761393 + z * 668265263 + seed * 2147483647) & 0xffffffff
    h = ((h ^ (h >> 13)) * 1274126177) & 0xffffffff
    return ((h ^ (h >> 16)) & 0xffff) / 65535.0


def value_noise(x, z, scale, seed):
    fx, fz = x / scale, z / scale
    x0, z0 = int(math.floor(fx)), int(math.floor(fz))
    tx, tz = fx - x0, fz - z0
    tx = tx * tx * (3 - 2 * tx)
    tz = tz * tz * (3 - 2 * tz)
    a = hash2(x0, z0, seed); b = hash2(x0 + 1, z0, seed)
    c = hash2(x0, z0 + 1, seed); d = hash2(x0 + 1, z0 + 1, seed)
    return (a + (b - a) * tx) * (1 - tz) + (c + (d - c) * tx) * tz


def hch(h):
    return '.' if h is None else '0123456789abcdef'[h]


def builtin(path, name):
    """a world file as C: world_builtin.c (committed, as mausrun's levels_builtin.c)"""
    out = sys.stdout
    out.write('/* GENERATED by gen_world.py --builtin from %s: do not edit */\n' % path.split('/')[-1])
    out.write('const char %s[] =\n' % name)
    for line in open(path):
        line = line.rstrip('\n').replace('\\', '\\\\').replace('"', '\\"')
        out.write('\t"%s\\n"\n' % line)
    out.write('\t"";\n')


def main():
    args = sys.argv[1:]
    if args and args[0] == '--builtin':
        builtin(args[1], args[2])
        return
    size = 128
    if args and args[0] == '--size':
        size = int(args[1]); args = args[2:]
    meta, rows = parse_level(args[0])
    nrows, ncols = len(rows), len(rows[0])
    N = size
    sea = 2                       # the sea's surface, in blocks
    base = 4                      # the meadow's ground (the old floor, row 11)

    # -- the path: a winding line across the island, west to east --
    # sampled finely, then walked by arc length: old column c at c * step
    margin = 14
    amp = (N - 2 * margin) * 0.30
    waves = max(1.5, N / 64.0)
    pts = []
    for i in range(4001):
        t = i / 4000.0
        x = margin + t * (N - 2 * margin)
        z = N / 2 + amp * math.sin(t * math.pi * waves) * (0.6 + 0.4 * math.cos(t * math.pi * 1.3))
        pts.append((x, z))
    arc = [0.0]
    for i in range(1, len(pts)):
        arc.append(arc[-1] + math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]))
    total = arc[-1]
    step = total / ncols          # tiles a column along the path

    def along(s):
        """the point and the unit direction at arc length s"""
        lo, hi = 0, len(arc) - 1
        while hi - lo > 1:
            mid = (lo + hi) // 2
            if arc[mid] <= s: lo = mid
            else: hi = mid
        a, b = pts[lo], pts[hi]
        seg = arc[hi] - arc[lo] or 1.0
        t = (s - arc[lo]) / seg
        x, z = a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t
        dx, dz = b[0] - a[0], b[1] - a[1]
        l = math.hypot(dx, dz) or 1.0
        return x, z, dx / l, dz / l

    # -- the old level, column by column --
    def floor_row(c):
        for r in range(nrows):
            if rows[r][c] in '=#K~':
                return r
        return None

    col_h, col_water = [], []
    for c in range(ncols):
        r = floor_row(c)
        if r is None:
            col_h.append(None); col_water.append(None)
            continue
        ch = rows[r][c]
        if ch == '~':
            # a pond: its bed below, the water at the old surface
            bed = r
            while bed < nrows and rows[bed][c] == '~':
                bed += 1
            col_h.append(max(1, nrows - bed)); col_water.append(nrows - r)
        else:
            col_h.append(nrows - r); col_water.append(None)

    # -- the island: ground everywhere, the sea outside an irregular coast --
    ground = [[None] * N for _ in range(N)]
    surface = [['g'] * N for _ in range(N)]
    water = [[None] * N for _ in range(N)]
    for z in range(N):
        for x in range(N):
            dx, dz = (x - N / 2) / (N / 2), (z - N / 2) / (N / 2)
            d = math.hypot(dx, dz) + (value_noise(x, z, N / 6.0, 7) - 0.5) * 0.35
            if d > 0.93:
                ground[z][x] = 1; surface[z][x] = 's'; water[z][x] = sea
            elif d > 0.84:
                ground[z][x] = 3; surface[z][x] = 's'
            else:
                # broad plateaus: few edges, so few faces to draw
                n = value_noise(x, z, N / 5.0, 3) * 0.8 + value_noise(x, z, N / 10.0, 5) * 0.2
                h = base
                if n > 0.60: h = base + 1
                if n > 0.74: h = base + 2
                if n < 0.28: h = base - 1
                ground[z][x] = h
    # no specks: a tile unlike most of its neighbours takes theirs
    for _ in range(3):
        g2 = [row[:] for row in ground]
        for z in range(1, N - 1):
            for x in range(1, N - 1):
                if water[z][x] is not None or ground[z][x] is None:
                    continue
                count = {}
                for dz in (-1, 0, 1):
                    for dx in (-1, 0, 1):
                        if dx or dz:
                            v = ground[z + dz][x + dx]
                            count[v] = count.get(v, 0) + 1
                best = max(count, key=lambda v: count[v])
                if count[best] >= 5 and best is not None:
                    g2[z][x] = best
        ground = g2

    # -- the path: five tiles wide, each old column's floor --
    things, blocks = [], []
    path_cells = {}
    sub = 4
    for c in range(ncols):
        for k in range(sub):
            s = (c + (k + 0.5) / sub) * step
            px, pz, ux, uz = along(s)
            for o in range(-2, 3):
                for o2 in (0.0, 0.5):
                    x = int(round(px - uz * (o + o2 * (1 if o >= 0 else -1))))
                    z = int(round(pz + ux * (o + o2 * (1 if o >= 0 else -1))))
                    if 0 <= x < N and 0 <= z < N:
                        path_cells[(x, z)] = c
    # a chasm is a little wider than the path, so it is a gap, not a notch
    for (x, z), c in path_cells.items():
        h = col_h[c]
        surface[z][x] = 'p'
        ground[z][x] = h
        water[z][x] = col_water[c]
        if h is None:
            for ddx in (-1, 0, 1):
                for ddz in (-1, 0, 1):
                    xx, zz = x + ddx, z + ddz
                    if 0 <= xx < N and 0 <= zz < N and (xx, zz) not in path_cells:
                        ground[zz][xx] = None
                        water[zz][xx] = None
    # the path's edges: the ground beside it no higher than a step above it
    for (x, z), c in path_cells.items():
        h = ground[z][x]
        if h is None:
            continue
        for ddx in (-1, 0, 1):
            for ddz in (-1, 0, 1):
                xx, zz = x + ddx, z + ddz
                if 0 <= xx < N and 0 <= zz < N and (xx, zz) not in path_cells:
                    g = ground[zz][xx]
                    if g is not None and g > h + 1 and water[zz][xx] is None:
                        ground[zz][xx] = h + 1

    # -- what stands on the old run: on the path's middle --
    def place(c, r, ch):
        s = (c + 0.5) * step
        px, pz, _, _ = along(s)
        x, z = int(round(px)), int(round(pz))
        y = nrows - 1 - r
        return x, z, y

    BLOCKS = 'B?-SK^'
    THINGS = 'cCZFOHG*Mwbmlkh'
    for r in range(nrows):
        for c in range(ncols):
            ch = rows[r][c]
            if ch in BLOCKS and floor_row(c) != r:
                blocks.append((place(c, r, ch), ch))
            elif ch in THINGS:
                things.append((place(c, r, ch), ch))
            elif ch == 'P':
                blocks.append((place(c, r, ch), '-'))

    out = sys.stdout
    name = meta.get('name', 'A World')
    out.write('# mausrun3d -- a world, made by gen_world.py from mausrun\'s %s\n' % args[0].split('/')[-1])
    out.write('# (docs/mausrun3d.md, "Worlds"): its run is the path across the island.\n')
    out.write('name %s\n' % name)
    out.write('theme %s\n' % meta.get('theme', 'meadow'))
    out.write('time %s\n' % meta.get('time', 'day'))
    out.write('size %d\n' % N)
    out.write('ground\n')
    for z in range(N):
        out.write(''.join(hch(ground[z][x]) for x in range(N)) + '\n')
    out.write('surface\n')
    for z in range(N):
        out.write(''.join(surface[z][x] for x in range(N)) + '\n')
    out.write('water\n')
    for z in range(N):
        out.write(''.join(hch(water[z][x]) for x in range(N)) + '\n')
    out.write('blocks\n')
    seen = set()
    for (x, z, y), ch in blocks:
        if (x, z, y) in seen or not (0 <= x < N and 0 <= z < N) or y > HMAX:
            continue
        seen.add((x, z, y))
        out.write('%d %d %d %s\n' % (x, z, y, ch))
    out.write('things\n')
    for (x, z, y), ch in things:
        if 0 <= x < N and 0 <= z < N:
            out.write('%d %d %d %s\n' % (x, z, y, ch))
    out.write('end\n')


if __name__ == '__main__':
    main()
