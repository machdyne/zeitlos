#!/usr/bin/env python3
"""Writes fontdata.c: the three font files the benchmark draws with, as
C arrays, so it needs no filesystem under the simulator."""
import os, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "data", "font")
out = ["/* generated by gen_fontdata.py -- do not edit */", "#include <stdint.h>"]
for var, rel in (("f_sans", "zhf/sans.zhf"), ("f_serif", "zhf/serif.zhf"), ("f_m9x15", "zfn/m9x15.zfn")):
    b = open(os.path.join(root, rel), "rb").read()
    out.append("const uint8_t %s[%d] = {" % (var, len(b)))
    for i in range(0, len(b), 20):
        out.append("\t" + ",".join(str(x) for x in b[i:i + 20]) + ",")
    out.append("};")
    out.append("const uint32_t %s_len = %d;" % (var, len(b)))
open(sys.argv[1] if len(sys.argv) > 1 else "fontdata.c", "w").write("\n".join(out) + "\n")
