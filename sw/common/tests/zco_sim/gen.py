#!/usr/bin/env python3
"""Writes jpgdata.c: the squirrel JPEG as a C array, so the simulator
test needs no filesystem."""
import os, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "..")
b = open(os.path.join(root, "sw/data/images/squirrel.jpg"), "rb").read()
out = ["/* generated by gen.py -- do not edit */", "#include <stdint.h>",
       "const uint8_t jpg[%d] = {" % len(b)]
for i in range(0, len(b), 24):
    out.append("\t" + ",".join(str(x) for x in b[i:i + 24]) + ",")
out += ["};", "const uint32_t jpg_len = %d;" % len(b)]
open(sys.argv[1], "w").write("\n".join(out) + "\n")
