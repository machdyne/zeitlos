#!/usr/bin/env python3
# Test data for lz4.c: real RV32IM code (a slice of libc.a), compressed
# by tools/mkzar.py's lz4_compress -- the same encoder that packs the
# OS's compressed executables -- and written out as blob.h.
import sys, os
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, '..', '..', '..', 'tools'))
import mkzar
src = sys.argv[1]
n = int(sys.argv[2]) if len(sys.argv) > 2 else 12288
data = open(src, 'rb').read()[8192:8192 + n]
comp = bytes(mkzar.lz4_compress(data))
assert mkzar.lz4_decompress(comp, len(data)) == data
def arr(name, b):
    s = 'static const uint8_t %s[%d] __attribute__((aligned(4))) = {\n' % (name, len(b))
    for i in range(0, len(b), 16):
        s += '\t' + ', '.join('0x%02x' % x for x in b[i:i+16]) + ',\n'
    return s + '};\n'
h = 2166136261
for x in data:
    h = ((h ^ x) * 16777619) & 0xffffffff
with open(os.path.join(here, 'blob.h'), 'w') as f:
    f.write('/* generated by gen.py: %d bytes of %s, LZ4 %d bytes */\n' % (len(data), os.path.basename(src), len(comp)))
    f.write('#define ORIG_LEN %du\n#define COMP_LEN %du\n#define ORIG_FNV 0x%08xu\n' % (len(data), len(comp), h))
    f.write(arr('orig', data))
    f.write(arr('comp', comp))
print(len(data), len(comp), hex(h))
