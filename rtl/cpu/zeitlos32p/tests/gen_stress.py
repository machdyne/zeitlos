#!/usr/bin/env python3
#
# Zeitlos SOC -- random stress programs for zeitlos32p (make stress).
# Copyright (c) 2026 Lone Dynamics Corporation. All rights reserved.
#
# No golden model: the program runs on zeitlos32 and on zeitlos32p
# side by side (tb_mpu_lockstep.v: zeitlos32p on the real split cache)
# and every register write and store must match. What it is aimed at
# is what zeitlos32's gen_random.py (straight-line ALU code) does not
# reach: loads and stores of every size through pointer registers that
# are reloaded from memory just before use -- having held a misaligned
# value until then -- branches and small loops over them, calls,
# multiply/divide in the middle, with every interrupt masked so that a
# fault the pipeline imagines halts it at once.
#
#   gen_stress.py --seed N [--blocks N] > prog/t_st_N.S
#
# Memory: code runs from main memory (the image's alias at
# 0x4000_0000, cached on zeitlos32p); data at 0x4000_8000 (a 2KB
# region and a pointer table), never fetched.

import argparse, random

p = argparse.ArgumentParser()
p.add_argument('--seed', type=int, default=1)
p.add_argument('--blocks', type=int, default=60)
p.add_argument('--irq', action='store_true',
    help='for tb_irq_stress.v: open IRQ 3, count it at COUNTER, dump every register at the end')
a = p.parse_args()
R = random.Random(a.seed)

DATA = 0x40008000          # 2KB region
TABLE = 0x40008800         # 16 pointers into it
PTRS = ['s0', 's1', 's2', 's3']     # pointer registers
TAB = 's4'                 # table base
VALS = ['a0', 'a1', 'a2', 'a3', 'a4', 'a5', 'a6', 'a7', 't2', 't3', 't4', 's5', 's6']
CNT = 's7'                 # loop counter
out = []
def e(s): out.append('\t' + s)
lab = [0]
def L():
    lab[0] += 1
    return '.Ls%d' % lab[0]

def rv(): return R.choice(VALS)

def alu():
    op = R.choice(['add', 'sub', 'xor', 'or', 'and', 'sll', 'srl', 'sra', 'slt', 'sltu',
                   'addi', 'xori', 'ori', 'andi', 'slli', 'srli', 'srai', 'slti', 'lui'])
    d = rv()
    if op == 'lui':
        e('lui %s, 0x%x' % (d, R.randrange(1 << 20)))
    elif op in ('slli', 'srli', 'srai'):
        e('%s %s, %s, %d' % (op, d, rv(), R.randrange(32)))
    elif op.endswith('i'):
        e('%s %s, %s, %d' % (op, d, rv(), R.randrange(-2048, 2048)))
    else:
        e('%s %s, %s, %s' % (op, d, rv(), rv()))

def muldiv():
    op = R.choice(['mul', 'mulh', 'mulhu', 'mulhsu', 'div', 'divu', 'rem', 'remu'])
    e('%s %s, %s, %s' % (op, rv(), rv(), rv()))

def mem(ptr):
    sz = R.choice([1, 2, 4, 4, 4])
    off = R.randrange(0, 64 // sz) * sz
    if R.random() < 0.5:
        e('%s %s, %d(%s)' % ({1: 'sb', 2: 'sh', 4: 'sw'}[sz], rv(), off, ptr))
    else:
        e('%s %s, %d(%s)' % (R.choice({1: ['lb', 'lbu'], 2: ['lh', 'lhu'], 4: ['lw']}[sz]), rv(), off, ptr))

def reload(ptr, junk=True):
    # the base register held a misaligned value until the very load
    # that gives it its pointer
    if junk:
        e('li %s, %d' % (ptr, R.choice([1, 2, 3, 0x1dca, -1, 0x7fffffff])))
    e('lw %s, %d(%s)' % (ptr, 4 * R.randrange(16), TAB))

def block():
    k = R.random()
    ptr = R.choice(PTRS)
    if k < 0.30:                     # reload, then use at once
        reload(ptr)
        for _ in range(R.randrange(1, 4)): mem(ptr)
    elif k < 0.45:                   # a chain: a pointer loaded through another
        q = R.choice([x for x in PTRS if x != ptr])
        reload(q, junk=False)
        e('li %s, 3' % ptr)
        e('lw %s, %d(%s)' % (ptr, 4 * R.randrange(16), TAB))
        mem(ptr)
        mem(q)
    elif k < 0.60:                   # a branch over a few
        t = L()
        e('%s %s, %s, %s' % (R.choice(['beq', 'bne', 'blt', 'bge', 'bltu', 'bgeu']), rv(), rv(), t))
        for _ in range(R.randrange(1, 4)): R.choice([alu, lambda: mem(ptr)])()
        out.append(t + ':')
    elif k < 0.72:                   # a small loop
        t = L()
        e('li %s, %d' % (CNT, R.randrange(1, 5)))
        out.append(t + ':')
        for _ in range(R.randrange(1, 4)): R.choice([alu, lambda: mem(ptr), lambda: reload(ptr)])()
        e('addi %s, %s, -1' % (CNT, CNT))
        e('bnez %s, %s' % (CNT, t))
    elif k < 0.80:                   # a call
        e('jal ra, leaf%d' % R.randrange(4))
    elif k < 0.88:
        muldiv()
    else:
        for _ in range(R.randrange(1, 5)): alu()

print('/* generated by gen_stress.py --seed %d --blocks %d */' % (a.seed, a.blocks))
print('#include "test.h"')
print('#define maskirq(_rd, _rs) .word ((0b0000011 << 25) | ((_rs) << 15) | (0b110 << 12) | ((_rd) << 7) | 0b0001011)')
print('\t.section .text\n\t.option norelax\n\t.globl _start\n_start:\n\tj _boot\n\tnop\n\tnop\n\tnop')
if a.irq:
    # IRQ 3 only (the faults stay masked: one the pipeline imagines
    # still halts it): count at COUNTER and return
    print('#define setq(_qd, _rs) .word ((0b0000001 << 25) | ((_rs) << 15) | (0b010 << 12) | ((_qd) << 7) | 0b0001011)')
    print('#define getq(_rd, _qs) .word ((0b0000000 << 25) | ((_qs) << 15) | (0b100 << 12) | ((_rd) << 7) | 0b0001011)')
    print('#define retirq() .word ((0b0000010 << 25) | 0b0001011)')
    print('\t.org 0x10\n\tsetq(2, 1)\n\tsetq(3, 2)\n\tli x1, 0x40008c00\n\tlw x2, 0(x1)\n\taddi x2, x2, 1\n\tsw x2, 0(x1)\n\tgetq(1, 2)\n\tgetq(2, 3)\n\tretirq()')
else:
    print('\t.org 0x10\n\tTEST_FAIL 999\t\t\t/* no interrupt may be raised */')
print('_boot:')
print('\tli a0, %d\n\tmaskirq(0, 10)' % (~(1 << 3) if a.irq else -1))
print('\tla t0, _main\n\tli t1, 0x40000000\n\tadd t0, t0, t1\n\tjr t0\t\t\t/* on, from main memory */')
print('_main:')
# the table: 16 aligned pointers into the region
print('\tli %s, 0x%x' % (TAB, TABLE))
for i in range(16):
    print('\tli t2, 0x%x\n\tsw t2, %d(%s)' % (DATA + 4 * R.randrange(0, (2048 - 64) // 4), 4 * i, TAB))
for r in PTRS:
    print('\tlw %s, %d(%s)' % (r, 4 * R.randrange(16), TAB))
for r in VALS:
    print('\tli %s, 0x%x' % (r, R.randrange(1 << 32)))
for _ in range(a.blocks):
    block()
print('\n'.join(out))
# the region and every register into the record, then pass
print('\tli t2, 0x%x' % DATA)
print('\tli t3, 0x%x' % (DATA + 2048))
print('1:\tlw t4, 0(t2)\n\taddi t2, t2, 4\n\tbne t2, t3, 1b')
if a.irq:
    # every register into memory (0x4000_8a00), for the comparison
    print('\tli t2, 0x40008a00')
    for i, r in enumerate(PTRS + VALS + [CNT]):
        print('\tsw %s, %d(t2)' % (r, 4 * i))
print('\tTEST_PASS')
for i in range(4):
    print('leaf%d:' % i)
    out2 = []
    for _ in range(R.randrange(1, 4)):
        d = R.choice(VALS)
        out2.append('\t%s %s, %s, %d' % (R.choice(['addi', 'xori', 'ori']), d, R.choice(VALS), R.randrange(-2048, 2048)))
    print('\n'.join(out2))
    print('\tret')
