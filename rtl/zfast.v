/*
 * Zeitlos SOC
 * Copyright (c) 2026 Lone Dynamics Corporation. All rights reserved.
 *
 * Fast zlink -- the link's top tier on the SATA-style DS port of a
 * Sechzig module (Mozart): two LVDS pairs, one each way, at up
 * to 100 Mbit/s -- about 10 MB/s of payload. docs/zlink.md, "Fast".
 * EXPERIMENTAL and off by default: a build asks for it (`ZLINK_FAST,
 * rtl/boards.vh).
 *
 * The same line as the GPIO stream engine's zlink mode (rtl/gpio_stream.v)
 * -- 8b/10b, K28.5 to align and fill, the same clock recovery rule --
 * eight times faster, so the same software protocol runs over it.
 *
 * -- Clocks --
 *
 *   clk     the bus clock (48 MHz): the registers, the CPU's ends of the
 *           FIFOs
 *   clk100  the datapath: one bit a clock at 100 Mbit/s
 *   clk200  the pads (rtl/zfast_pad.v): an output register, and an input
 *           register sampling on both edges -- 400 MS/s, four samples a
 *           bit
 *
 * clk100 and clk200 come from one PLL (rtl/clk/pll0.v), so moving bits
 * between them is plain registers: a TX bit is held for two 200 MHz
 * clocks; RX samples arrive two per 200 MHz clock and leave four per
 * 100 MHz clock. The bus clock is a different PLL on DDR3 boards, so
 * clk <-> clk100 is fully asynchronous: dual-clock FIFOs with Gray-coded
 * pointers, one block RAM each way, and two-flop synchronisers for the
 * rest.
 *
 * -- Rates --
 *
 * 100, 50 or 25 Mbit/s (FCTL.RATE): a slower rate holds each TX bit for
 * 2 or 4 clocks, and the receiver keeps every 2nd or 4th sample -- still
 * four to a bit. For longer or poorer cables.
 *
 * -- Clock recovery --
 *
 * The engine's rule, unchanged: a sample that differs from the one
 * before restarts the bit; the bit is taken two samples later, in its
 * middle. The engine takes one sample a clock; this takes four, so the
 * rule is unrolled four times in one clock, and gives 0, 1 or 2 bits
 * (two only when the far end's clock runs fast). The bits then go to
 * the alignment and symbol logic one clock later, unrolled twice and
 * written out flat; the 8b/10b decode has a clock of its own after
 * that, and its verdict another. At 100 MHz on an ECP5 every one of
 * those registers is needed: with any two stages merged, the 100 MHz
 * clock does not close (mozart_ml1, nextpnr-ecp5 0.11.1: 69 MHz with
 * the FIFO's Gray-to-binary unregistered, 95 with the symbol select
 * in the alignment stage, 105.7 as it is).
 *
 * -- Pairs and roles --
 *
 * DS1 and DS2 are both bidirectional: FCTL.TXSEL says which one this end
 * drives (or neither), FCTL.RXSEL which one it listens to. Two Mozarts on
 * a straight SATA cable both have DS1 on the same wires, so one of them
 * must transmit on DS2 -- software works out which (sw/common/zlink_fast.c),
 * the way soft zlink works out its wires. On a Sechzig ML2, DS2 is a C/D
 * pair, which cannot drive true LVDS: TX_DS2 = 0 and this block never
 * drives it, whatever FCTL says. (nextpnr does not stop a design driving
 * LVDS from a C/D pair; this is the only thing that does.)
 *
 * -- Registers --
 *
 * The engine's layout, so the software is the same shape:
 *
 *   0  FCTL    [0] EN, [2:1] TXSEL (0 none, 1 DS1, 2 DS2), [3] RXSEL (0 DS1,
 *              1 DS2), [4] RXEN, [5] LOOP (TX straight to RX inside), [7:6]
 *              RATE (0 100, 1 50, 2 25 Mbit/s), [8] TXINV, [9] RXINV.
 *              Reads [16]: DS2 can transmit (TX_DS2)
 *   3  FSTAT   [10:0] TX level, [11] busy, [12] RX overrun, [13] TX overflow,
 *              [14] aligned, [15] K symbol popped by FRX4, [26:16] RX level
 *   4  FTX     push one entry: [8] K flag, [7:0] byte
 *   5  FTX4    push four data bytes, byte 0 first
 *   6  FRX     pop one: [9] valid, [8] K, [7:0] byte; 0 when empty
 *   7  FRX4    pop four data bytes -- only when four are waiting, else 0
 *   8  FERR    [15:0] code errors and misplaced commas, saturating
 *   9  FFLUSH  [0] TX FIFO, [1] RX FIFO, [2] sticky flags and FERR
 *   10 FLOCK   test-and-set: reading takes it, 0 back means it was free
 *
 * FIFOs of 1024 entries each way. Bus: gpio.v holds `acc` until `done`.
 */

module zfast #(
	parameter TX_DS2 = 1		// DS2 can transmit: an A/B pair
)
(
	input clk,
	input rst,
	input acc,
	input we,
	input [3:0] ra,
	input [31:0] wd,
	output reg done,
	output reg [31:0] rdo,

	input clk100,
	input clk200,
	input fclk_ok,				// the PLL is locked

	inout ds1,
	inout ds2
);

	// The 8b/10b code: the engine's (rtl/gpio_stream.v), generated by the
