	endfunction

	// 3b/4b for data, RD- form (bit 0 = f), same flag layout as
	// enc6. y = 7 here is the primary form; the A7 alternate is
	// chosen by the caller.
	function [5:0] enc4;
		input [2:0] y;
		case (y)
			3'd0: enc4 = {1'b0, 1'b1, 4'b1101};
			3'd1: enc4 = {1'b0, 1'b0, 4'b1001};
			3'd2: enc4 = {1'b0, 1'b0, 4'b1010};
			3'd3: enc4 = {1'b1, 1'b0, 4'b0011};
			3'd4: enc4 = {1'b0, 1'b1, 4'b1011};
			3'd5: enc4 = {1'b0, 1'b0, 4'b0101};
			3'd6: enc4 = {1'b0, 1'b0, 4'b0110};
			3'd7: enc4 = {1'b0, 1'b1, 4'b0111};
		endcase
	endfunction

	// 3b/4b for K28.y when the symbol STARTS at RD- (after the
	// 001111 half); bit 4: unbalanced. From RD+ the whole
	// symbol is the complement.
	function [4:0] enc4k28;
		input [2:0] y;
		case (y)
			3'd0: enc4k28 = {1'b1, 4'b0010};
			3'd1: enc4k28 = {1'b0, 4'b1001};
			3'd2: enc4k28 = {1'b0, 4'b1010};
			3'd3: enc4k28 = {1'b0, 4'b1100};
			3'd4: enc4k28 = {1'b1, 4'b0100};
			3'd5: enc4k28 = {1'b0, 4'b0101};
			3'd6: enc4k28 = {1'b0, 4'b0110};
			3'd7: enc4k28 = {1'b1, 4'b0001};
		endcase
	endfunction

	// 6b/5b decode: {valid, x}. Both RD forms map to the same x.
	function [5:0] dec6;
		input [5:0] s;
		case (s)
			6'd5: dec6 = {1'b1, 5'd15};
			6'd6: dec6 = {1'b1, 5'd0};
			6'd7: dec6 = {1'b1, 5'd7};
			6'd9: dec6 = {1'b1, 5'd16};
			6'd10: dec6 = {1'b1, 5'd31};
			6'd11: dec6 = {1'b1, 5'd11};
			6'd12: dec6 = {1'b1, 5'd24};
			6'd13: dec6 = {1'b1, 5'd13};
			6'd14: dec6 = {1'b1, 5'd14};
			6'd17: dec6 = {1'b1, 5'd1};
			6'd18: dec6 = {1'b1, 5'd2};
			6'd19: dec6 = {1'b1, 5'd19};
			6'd20: dec6 = {1'b1, 5'd4};
			6'd21: dec6 = {1'b1, 5'd21};
			6'd22: dec6 = {1'b1, 5'd22};
			6'd23: dec6 = {1'b1, 5'd23};
			6'd24: dec6 = {1'b1, 5'd8};
			6'd25: dec6 = {1'b1, 5'd25};
			6'd26: dec6 = {1'b1, 5'd26};
			6'd27: dec6 = {1'b1, 5'd27};
			6'd28: dec6 = {1'b1, 5'd28};
			6'd29: dec6 = {1'b1, 5'd29};
			6'd30: dec6 = {1'b1, 5'd30};
			6'd33: dec6 = {1'b1, 5'd30};
			6'd34: dec6 = {1'b1, 5'd29};
			6'd35: dec6 = {1'b1, 5'd3};
			6'd36: dec6 = {1'b1, 5'd27};
			6'd37: dec6 = {1'b1, 5'd5};
			6'd38: dec6 = {1'b1, 5'd6};
			6'd39: dec6 = {1'b1, 5'd8};
			6'd40: dec6 = {1'b1, 5'd23};
			6'd41: dec6 = {1'b1, 5'd9};
			6'd42: dec6 = {1'b1, 5'd10};
			6'd43: dec6 = {1'b1, 5'd4};
			6'd44: dec6 = {1'b1, 5'd12};
			6'd45: dec6 = {1'b1, 5'd2};
			6'd46: dec6 = {1'b1, 5'd1};
			6'd49: dec6 = {1'b1, 5'd17};
			6'd50: dec6 = {1'b1, 5'd18};
			6'd51: dec6 = {1'b1, 5'd24};
			6'd52: dec6 = {1'b1, 5'd20};
			6'd53: dec6 = {1'b1, 5'd31};
			6'd54: dec6 = {1'b1, 5'd16};
			6'd56: dec6 = {1'b1, 5'd7};
			6'd57: dec6 = {1'b1, 5'd0};
			6'd58: dec6 = {1'b1, 5'd15};
			default: dec6 = 6'd0;
		endcase
	endfunction

	// 4b/3b decode for data: {valid, y}. The A7 forms decode to 7.
	function [3:0] dec4;
		input [3:0] s;
		case (s)
			4'd1: dec4 = {1'b1, 3'd7};
			4'd2: dec4 = {1'b1, 3'd0};
			4'd3: dec4 = {1'b1, 3'd3};
			4'd4: dec4 = {1'b1, 3'd4};
			4'd5: dec4 = {1'b1, 3'd5};
			4'd6: dec4 = {1'b1, 3'd6};
			4'd7: dec4 = {1'b1, 3'd7};
			4'd8: dec4 = {1'b1, 3'd7};
			4'd9: dec4 = {1'b1, 3'd1};
			4'd10: dec4 = {1'b1, 3'd2};
			4'd11: dec4 = {1'b1, 3'd4};
			4'd12: dec4 = {1'b1, 3'd3};
			4'd13: dec4 = {1'b1, 3'd0};
			4'd14: dec4 = {1'b1, 3'd7};
			default: dec4 = 4'd0;
		endcase
	endfunction

	// 4b/3b decode for K28.y, from the RD- form of the symbol
	// (001111 ....); the RD+ form is the complement of the whole
	// symbol, so the caller complements first.
	function [3:0] dec4k28;
		input [3:0] s;
		case (s)
			4'b0010: dec4k28 = {1'b1, 3'd0};
			4'b1001: dec4k28 = {1'b1, 3'd1};
			4'b1010: dec4k28 = {1'b1, 3'd2};
			4'b1100: dec4k28 = {1'b1, 3'd3};
			4'b0100: dec4k28 = {1'b1, 3'd4};
			4'b0101: dec4k28 = {1'b1, 3'd5};
			4'b0110: dec4k28 = {1'b1, 3'd6};
			4'b0001: dec4k28 = {1'b1, 3'd7};
			default: dec4k28 = 4'd0;
		endcase
	endfunction
	// -- end generated --

	localparam [9:0] K28_5_N = 10'h17C;	// 0011111010, a first
	localparam [9:0] K28_5_P = 10'h283;	// 1100000101

	// {rd_out, symbol} for (k, byte) at running disparity rd (1 = RD+).
	// Only K28.y and K23/27/29/30.7 are control symbols; zlink uses
	// K28.5 (idle/comma) and K27.7, K29.7, K30.7 (framing, Round 2).
	function [10:0] enc8b10b;
		input k;
		input [7:0] b;
		input rd;
		reg [7:0] e6;
		reg [5:0] e4;
		reg [4:0] e4k;
		reg [5:0] s6;
		reg [3:0] s4;
		reg rd1, rd2, alt;
		begin
			if (k && b[4:0] == 5'd28) begin
				e4k = enc4k28(b[7:5]);
				// 001111 + the RD- 4b half; the whole symbol is
				// complemented from RD+. K28's 6b half is unbalanced, so
				// the disparity flips unless the 4b half flips it back.
				s6 = rd ? 6'b000011 : 6'b111100;
				s4 = rd ? ~e4k[3:0] : e4k[3:0];
				rd2 = rd ^ 1'b1 ^ e4k[4];
			end else begin
				e6 = enc6(b[4:0]);
				s6 = (rd && (e6[6] | e6[7])) ? ~e6[5:0] : e6[5:0];
				rd1 = rd ^ e6[6];
				if (k || b[7:5] == 3'd7) begin
					// Kx.7 always uses the alternate; D.x.7 only for
					// the six (x, rd) pairs that would otherwise make a
					// run of five.
					alt = k ||
						(!rd1 && (b[4:0] == 5'd17 || b[4:0] == 5'd18 ||
						          b[4:0] == 5'd20)) ||
						(rd1 && (b[4:0] == 5'd11 || b[4:0] == 5'd13 ||
						         b[4:0] == 5'd14));
					// A7 0111/1000 and P7 1110/0001, a..j order reversed
					s4 = alt ? (rd1 ? 4'b0001 : 4'b1110)
					         : (rd1 ? 4'b1000 : 4'b0111);
					rd2 = ~rd1;
				end else begin
					e4 = enc4(b[7:5]);
					s4 = (rd1 && (e4[4] | e4[5])) ? ~e4[3:0] : e4[3:0];
					rd2 = rd1 ^ e4[4];
				end
			end
			enc8b10b = { rd2, s4, s6 };
		end
	endfunction

	// {valid, k, byte}
	function [9:0] dec8b10b;
		input [9:0] s;
		reg [5:0] d6;
		reg [3:0] d4;
		reg k28, kx;
		begin
			k28 = (s[5:0] == 6'b111100) || (s[5:0] == 6'b000011);
			if (k28) begin
				d4 = dec4k28(s[5:0] == 6'b111100 ? s[9:6] : ~s[9:6]);
				dec8b10b = { d4[3], 1'b1, d4[2:0], 5'd28 };
			end else begin
				d6 = dec6(s[5:0]);
				d4 = dec4(s[9:6]);
				kx = (d6[4:0] == 5'd23 || d6[4:0] == 5'd27 ||
				      d6[4:0] == 5'd29 || d6[4:0] == 5'd30) &&
				     (s[9:6] == 4'b1110 || s[9:6] == 4'b0001);
				dec8b10b = { d6[5] & d4[3], kx, d4[2:0], d6[4:0] };
			end
		end
	endfunction


	function [10:0] g2b;		// Gray to binary, 11 bits
		input [10:0] g;
		integer n;
		begin
			g2b[10] = g[10];
			for (n = 9; n >= 0; n = n - 1) g2b[n] = g2b[n + 1] ^ g[n];
		end
	endfunction

	// ------------------------------------------------------------------
	// Bus side (clk): configuration
	// ------------------------------------------------------------------

	reg en, rxsel, rxen, loop, txinv, rxinv;
	reg [1:0] txsel, rate;
	reg lock;

	wire [31:0] fctl = { 15'd0, (TX_DS2 != 0), 6'd0, rxinv, txinv, rate,
	                     loop, rxen, rxsel, txsel, en };

	// ------------------------------------------------------------------
	// The FIFOs: TX written here (clk), read in clk100; RX the other way.
	// Pointers are 11 bits over 1024 entries -- the top bit tells full
	// from empty -- and cross as Gray code.
	// ------------------------------------------------------------------

	reg [8:0] txm [0:1023];
	reg [8:0] rxm [0:1023];

	reg [10:0] txw, rxr;				// clk
	reg [10:0] txr, rxw;				// clk100
	wire [10:0] txw_g = txw ^ (txw >> 1);
	wire [10:0] rxr_g = rxr ^ (rxr >> 1);
	reg [10:0] txr_g, rxw_g;			// registered in clk100, as they cross

	// clk100 pointers, seen from clk
	reg [10:0] txr_s1, txr_s2, rxw_s1, rxw_s2;
	always @(posedge clk) begin
		txr_s1 <= txr_g; txr_s2 <= txr_s1;
		rxw_s1 <= rxw_g; rxw_s2 <= rxw_s1;
	end
	wire [10:0] txr_c = g2b(txr_s2);
	wire [10:0] rxw_c = g2b(rxw_s2);
	wire [10:0] tx_level = txw - txr_c;
	wire [10:0] rx_level = rxw_c - rxr;
	wire tx_full = tx_level[10];

	// clk pointers, seen from clk100
	reg [10:0] txw_s1, txw_s2, rxr_s1, rxr_s2;
	reg [10:0] txw_gr, rxr_gr;			// registered in clk before crossing
	always @(posedge clk) begin
		txw_gr <= txw_g;
		rxr_gr <= rxr_g;
	end
	always @(posedge clk100) begin
		txw_s1 <= txw_gr; txw_s2 <= txw_s1;
		rxr_s1 <= rxr_gr; rxr_s2 <= rxr_s1;
	end
	// Gray to binary is a chain of ten XORs: registered, so it does not
	// share a 10 ns clock with what uses it (one clock later still only
	// makes the FIFOs more cautious)
	reg [10:0] txw_f = 11'd0, rxr_f = 11'd0;
	always @(posedge clk100) begin
		txw_f <= g2b(txw_s2);
		rxr_f <= g2b(rxr_s2);
	end

	// TX RAM: the CPU's write, the datapath's read
	reg tm_we;
	reg [9:0] tm_wa;
	reg [8:0] tm_wd;
	always @(posedge clk) if (tm_we) txm[tm_wa] <= tm_wd;
	reg [9:0] tm_ra;
	reg [8:0] tm_q;
	always @(posedge clk100) tm_q <= txm[tm_ra];

	// RX RAM: the datapath's write, the CPU's read
	reg rm_we;
	reg [9:0] rm_wa;
	reg [8:0] rm_wd;
	always @(posedge clk100) if (rm_we) rxm[rm_wa] <= rm_wd;
	reg [9:0] rm_ra;
	reg [8:0] rm_q;
	always @(posedge clk) rm_q <= rxm[rm_ra];

	// ------------------------------------------------------------------
	// clk100 events, counted on the bus side: each toggles a flag that
	// crosses through two flops; the bus side counts the changes. An
	// event happens at most once a symbol (10 clocks), so none is lost.
	// ------------------------------------------------------------------

	// Initial values, not resets: each is one end of a crossing, and a
	// reset would have to come from the other side's clock.
	reg err_t = 1'b0, ovr_t = 1'b0, aligned_f = 1'b0;
	reg [2:0] err_s = 3'd0, ovr_s = 3'd0;
	reg [1:0] al_s = 2'd0;
	always @(posedge clk) begin
		err_s <= { err_s[1:0], err_t };
		ovr_s <= { ovr_s[1:0], ovr_t };
		al_s <= { al_s[0], aligned_f };
	end
	wire err_ev = err_s[2] ^ err_s[1];
	wire ovr_ev = ovr_s[2] ^ ovr_s[1];
	wire aligned = al_s[1];

	reg rxovr, txovf, kword;
	reg [15:0] serr;
	reg txflush_req;					// toggled to ask clk100 to empty TX

	// ------------------------------------------------------------------
	// Bus side: the registers
	// ------------------------------------------------------------------

	wire busy = (tx_level != 11'd0);
	wire [31:0] fstat = { 5'd0, rx_level, kword, aligned, txovf, rxovr,
	                      busy, tx_level };

	reg [31:0] rmux;
	always @(*) begin
		case (ra)
		4'd0: rmux = fctl;
		4'd3: rmux = fstat;
		4'd8: rmux = { 16'd0, serr };
		4'd10: rmux = { 31'd0, lock };
		default: rmux = 32'd0;
		endcase
	end

	localparam S_IDLE = 2'd0, S_PUSH = 2'd1, S_POP = 2'd2, S_WAIT = 2'd3;
	reg [1:0] st;
	reg [31:0] stage;
	reg stk;
	reg [2:0] pcnt, pgot;
	reg pop4, rd_d;
	reg rd_q;				// rm_q holds a read issued two clocks ago
	always @(posedge clk) rd_q <= rd_d;

	always @(posedge clk) begin
		done <= 1'b0;
		tm_we <= 1'b0;
		rd_d <= 1'b0;

		if (rst) begin
			st <= S_IDLE;
			en <= 1'b0; rxsel <= 1'b0; rxen <= 1'b0; loop <= 1'b0;
			txinv <= 1'b0; rxinv <= 1'b0; txsel <= 2'd0; rate <= 2'd0;
			lock <= 1'b0;
			txw <= 11'd0;
			rxr <= 11'd0;
			rxovr <= 1'b0; txovf <= 1'b0; kword <= 1'b0;
			serr <= 16'd0;
			txflush_req <= 1'b0;
			rdo <= 32'd0;
			pcnt <= 3'd0;
		end else begin
			if (ovr_ev) rxovr <= 1'b1;
			if (err_ev && serr != 16'hFFFF) serr <= serr + 16'd1;

			case (st)
			S_IDLE: if (acc) begin
				if (we) begin
					case (ra)
					4'd0: begin
						en <= wd[0];
						// DS2 is never driven where it cannot be
						txsel <= (wd[2:1] == 2'd2 && TX_DS2 == 0) ? 2'd0 : wd[2:1];
						rxsel <= wd[3]; rxen <= wd[4]; loop <= wd[5];
						rate <= (wd[7:6] == 2'd3) ? 2'd2 : wd[7:6];
						txinv <= wd[8]; rxinv <= wd[9];
					end
					4'd9: begin
						if (wd[0]) txflush_req <= !txflush_req;
						if (wd[1]) rxr <= rxw_c;
						if (wd[2]) begin
							rxovr <= 1'b0; txovf <= 1'b0; kword <= 1'b0;
							serr <= 16'd0;
						end
					end
					4'd10: lock <= wd[0];
					default: ;
					endcase
					if (ra == 4'd4 || ra == 4'd5) begin
						stage <= wd;
						stk <= (ra == 4'd4) ? wd[8] : 1'b0;
						pcnt <= (ra == 4'd4) ? 3'd1 : 3'd4;
						st <= S_PUSH;
					end else begin
						done <= 1'b1;
						st <= S_WAIT;
					end
				end else begin
					if (ra == 4'd10) lock <= 1'b1;
					if ((ra == 4'd6 && rx_level != 11'd0) ||
					    (ra == 4'd7 && rx_level >= 11'd4)) begin
						pop4 <= (ra == 4'd7);
						pcnt <= (ra == 4'd7) ? 3'd4 : 3'd1;
						pgot <= 3'd0;
						rdo <= 32'd0;
						st <= S_POP;
					end else begin
						rdo <= rmux;
						done <= 1'b1;
						st <= S_WAIT;
					end
				end
			end

			// one entry a clock; a full FIFO drops it and says so
			S_PUSH: begin
				if (pcnt == 3'd0) begin
					done <= 1'b1;
					st <= S_WAIT;
				end else begin
					if (tx_full) txovf <= 1'b1;
					else begin
						tm_we <= 1'b1;
						tm_wa <= txw[9:0];
						tm_wd <= { stk, stage[7:0] };
						txw <= txw + 11'd1;
					end
					stage <= { 8'd0, stage[31:8] };
					stk <= 1'b0;
					pcnt <= pcnt - 3'd1;
				end
			end

			// one read issued a clock; each lands in rm_q two clocks
			// later (the address is registered too)
			S_POP: begin
				if (pcnt != 3'd0) begin
					rm_ra <= rxr[9:0];
					rxr <= rxr + 11'd1;
					pcnt <= pcnt - 3'd1;
					rd_d <= 1'b1;
				end
				if (rd_q) begin
					if (pop4) begin
						rdo <= { rm_q[7:0], rdo[31:8] };
						if (rm_q[8]) kword <= 1'b1;
					end else
						rdo <= { 22'd0, 1'b1, rm_q };
					pgot <= pgot + 3'd1;
					if (pgot + 3'd1 == (pop4 ? 3'd4 : 3'd1)) begin
						done <= 1'b1;
						st <= S_WAIT;
					end
				end
			end

			S_WAIT: if (!acc) st <= S_IDLE;
			endcase
		end
	end


	// ------------------------------------------------------------------
	// clk100: configuration, synchronised
	// ------------------------------------------------------------------

	wire [10:0] cfg = { fclk_ok && !rst, en, txsel, rxsel, rxen, loop, rate, txinv, rxinv };
	reg [10:0] cfg_s1 = 11'd0, cfg_f = 11'd0;
	reg [10:0] cfg_p = 11'd0;
	always @(posedge clk100) begin
		cfg_s1 <= cfg;
		cfg_f <= cfg_s1;
		cfg_p <= cfg_f;
	end
	wire f_rst   = !cfg_f[10];			// bus reset, or the PLL not locked
	wire f_on    = cfg_f[10] && cfg_f[9];
	wire [1:0] f_txsel = cfg_f[8:7];
	wire f_rxsel = cfg_f[6];
	wire f_rxen  = cfg_f[5];
	wire f_loop  = cfg_f[4];
	wire [1:0] f_rate = cfg_f[3:2];
	wire f_txinv = cfg_f[1];
	wire f_rxinv = cfg_f[0];

	// any change but RXEN restarts the datapath (not the FIFOs)
	wire dp_rst = !f_on || ((cfg_f ^ cfg_p) & 11'b111_1101_1111) != 11'd0;

	reg [1:0] fl_s = 2'd0;
	reg fl_p = 1'b0;
	always @(posedge clk100) begin
		fl_s <= { fl_s[0], txflush_req };
		fl_p <= fl_s[1];
	end
	wire tx_flush = fl_s[1] ^ fl_p;

	// ------------------------------------------------------------------
	// Pads (clk200)
	// ------------------------------------------------------------------

	reg txb;							// clk100: the bit on the wire
	reg oe1, oe2;						// clk100
	wire [1:0] q1, q2;

	zfast_pad p1 (.pad(ds1), .clk200(clk200), .oe(oe1), .d(txb), .q(q1));
	zfast_pad p2 (.pad(ds2), .clk200(clk200), .oe(oe2), .d(txb), .q(q2));

	// two samples a clk200, four a clk100: the 100 MHz clock takes the
	// last two pairs, oldest in bit 0
	reg [1:0] pair, pair_p;
	reg [3:0] quad;
	reg rsel200;
	always @(posedge clk200) begin
		rsel200 <= f_rxsel;
		pair <= rsel200 ? q2 : q1;
		pair_p <= pair;
		quad <= { pair, pair_p };
	end

	// ------------------------------------------------------------------
	// clk100: RX
	// ------------------------------------------------------------------

	reg [3:0] smp;
	always @(posedge clk100) smp <= f_loop ? {4{txb}} : quad;

	// keep every 1st, 2nd or 4th sample; a tick when four are in hand
	reg [1:0] gcnt;
	reg [3:0] gacc;
	reg tick;
	reg [3:0] s4;
	wire [3:0] smpi = smp ^ {4{f_rxinv}};
	always @(posedge clk100) begin
		tick <= 1'b0;
		if (dp_rst) begin
			gcnt <= 2'd0;
		end else begin
			gcnt <= gcnt + 2'd1;
			case (f_rate)
			2'd0: begin
				s4 <= smpi;
				tick <= 1'b1;
			end
			2'd1: begin
				gacc[1:0] <= { smpi[2], smpi[0] };
				if (gcnt[0]) begin
					s4 <= { smpi[2], smpi[0], gacc[1:0] };
					tick <= 1'b1;
				end
			end
			default: begin
				gacc <= { smpi[0], gacc[3:1] };
				if (gcnt == 2'd3) begin
					s4 <= { smpi[0], gacc[3:1] };
					tick <= 1'b1;
				end
			end
			endcase
		end
	end

	// Clock recovery, four steps a tick: {bits found (0-2), first, second}.
	// Each step is the engine's: an edge restarts the phase, the bit is
	// the sample at phase 2.
	reg rprev;
	reg [1:0] rph;

	function [5:0] cdr_step;			// { emit, bit, ph[1:0], prev, - }
		input x;
		input prev;
		input [1:0] ph;
		reg [1:0] p;
		begin
			p = (x != prev) ? 2'd0 : ph + 2'd1;
			cdr_step = { (p == 2'd2), x, p, x, 1'b0 };
		end
	endfunction

	reg [1:0] nb;					// bits this tick
	reg b0, b1;
	reg [5:0] c0, c1, c2, c3;
	reg [1:0] n_c;
	reg b0_c, b1_c;
	always @(*) begin
		c0 = cdr_step(s4[0], rprev, rph);
		c1 = cdr_step(s4[1], c0[1], c0[3:2]);
		c2 = cdr_step(s4[2], c1[1], c1[3:2]);
		c3 = cdr_step(s4[3], c2[1], c2[3:2]);
		n_c = 2'd0; b0_c = 1'b0; b1_c = 1'b0;
		if (c0[5]) begin if (n_c == 2'd0) b0_c = c0[4]; else b1_c = c0[4]; n_c = n_c + 2'd1; end
		if (c1[5]) begin if (n_c == 2'd0) b0_c = c1[4]; else b1_c = c1[4]; n_c = n_c + 2'd1; end
		if (c2[5]) begin if (n_c == 2'd0) b0_c = c2[4]; else b1_c = c2[4]; n_c = n_c + 2'd1; end
		if (c3[5]) begin if (n_c == 2'd0) b0_c = c3[4]; else b1_c = c3[4]; n_c = n_c + 2'd1; end
	end

	always @(posedge clk100) begin
		nb <= 2'd0;
		if (dp_rst) begin
			rprev <= 1'b0;
			rph <= 2'd0;
		end else if (tick) begin
			rprev <= c3[1];
			rph <= c3[3:2];
			nb <= (n_c > 2'd2) ? 2'd2 : n_c;
			b0 <= b0_c;
			b1 <= b1_c;
		end
	end

	// Alignment and symbols, a clock later: the engine's logic, for up
	// to two bits. A comma restarts the symbol count; ten bits after it
	// are a symbol.
	reg [9:0] rx10;
	reg [3:0] rbit;
	reg [9:0] sym_q;
	reg sym_v;
	reg al;

	// Two bits a clock, written out flat so that nothing waits on
	// anything it need not: both comma checks, and rbit's compares, come
	// straight from registers. Bit 0 (b0) is the older.
	//   comma         restarts the count; misplaced if aligned and the
	//                 count was not at a symbol's end: an error
	//   aligned, 9    the tenth bit: a symbol
	wire [9:0] n10_0 = { b0, rx10[9:1] };
	wire [9:0] n10_1 = { b1, b0, rx10[9:2] };
	wire cm0 = (n10_0 == K28_5_N) || (n10_0 == K28_5_P);
	wire cm1 = (n10_1 == K28_5_N) || (n10_1 == K28_5_P);
	wire e9 = rbit == 4'd9;
	wire e8 = rbit == 4'd8;
	wire [3:0] rbit1 = rbit + 4'd1;
	wire [3:0] rbit2 = rbit + 4'd2;

	wire sym0 = !cm0 && al && e9;
	wire err0 = cm0 && al && !e9;
	wire a0 = cm0 || al;
	wire [3:0] rb0 = (cm0 || (al && e9)) ? 4'd0 : al ? rbit1 : rbit;
	wire rb0_9 = !cm0 && (al ? e8 : e9);		// rb0 == 9
	wire rb0_0 = cm0 || (al && e9);				// rb0 == 0

	wire sym1 = !cm1 && a0 && rb0_9;
	wire err1 = cm1 && a0 && !rb0_9;
	wire a1 = cm1 || a0;
	wire [3:0] rb1 = (cm1 || (a0 && rb0_9)) ? 4'd0 :
	                 !a0 ? rb0 :
	                 rb0_0 ? 4'd1 :
	                 al ? rbit2 : rbit1;

	reg push, sym_v2, dec_ok;
	reg [8:0] push_d;
	reg [8:0] dsym_q;

	// both candidates, every clock, no enable; which one is chosen in
	// the decode stage (sym_q is only looked at with sym_v)
	reg [9:0] sq0, sq1;
	reg ssel;
	always @(posedge clk100) begin
		sq0 <= n10_0;
		sq1 <= n10_1;
		ssel <= nb == 2'd2 && sym1;
	end
	always @(*) sym_q = ssel ? sq1 : sq0;

	always @(posedge clk100) begin
		sym_v <= 1'b0;
		sym_v2 <= 1'b0;
		push <= 1'b0;
		if (dp_rst) begin
			// all ones: stale bits cannot complete a false comma
			// (rtl/gpio_stream.v found that the hard way)
			rx10 <= 10'h3FF;
			rbit <= 4'd0;
			al <= 1'b0;
		end else begin
			if (nb == 2'd1) begin
				rx10 <= n10_0; rbit <= rb0; al <= a0;
				sym_v <= sym0;
			end else if (nb == 2'd2) begin
				rx10 <= n10_1; rbit <= rb1; al <= a1;
				// a symbol ends at most once in two bits
				sym_v <= sym0 || sym1;
			end
			// decode a clock later, and act on it the clock after that:
			// off the sampling path
			if (sym_v) begin
				{ dec_ok, dsym_q } <= dec8b10b(sym_q);
				sym_v2 <= 1'b1;
			end
			if (sym_v2) begin
				if (dec_ok) begin
					push_d <= dsym_q;
					push <= f_rxen;
				end else begin
					al <= 1'b0;		// not a symbol: wait for the next comma
				end
			end
		end
		// any error this clock: one count (FERR is a rough measure)
		if (!dp_rst && ((nb != 2'd0 && err0) || (nb == 2'd2 && err1) || (sym_v2 && !dec_ok)))
			err_t <= !err_t;
	end

	always @(posedge clk100) aligned_f <= al;

	// into the RX FIFO; full drops it and says so
	wire [10:0] rx_lvl_f = rxw - rxr_f;
	always @(posedge clk100) begin
		rm_we <= 1'b0;
		if (f_rst) begin
			rxw <= 11'd0;
		end else if (push) begin
			if (rx_lvl_f[10]) ovr_t <= !ovr_t;
			else begin
				rm_we <= 1'b1;
				rm_wa <= rxw[9:0];
				rm_wd <= push_d;
				rxw <= rxw + 11'd1;
			end
		end
		rxw_g <= rxw ^ (rxw >> 1);
	end

	// ------------------------------------------------------------------
	// clk100: TX
	// ------------------------------------------------------------------

	reg [8:0] tx_byte;
	reg tx_have, tx_take, fpend, fpend2;
	wire tx_avail = txw_f != txr;			// an entry waiting
	reg [9:0] txsh;
	reg [3:0] txleft;
	reg [1:0] bcnt;
	reg rd;
	reg [10:0] enc_q;
	reg enc_data;
	reg [7:0] zl_run;

	// the bit ends every clock, every 2nd or every 4th
	wire bit_end = (f_rate == 2'd0) || (f_rate == 2'd1 && bcnt[0]) ||
	               (f_rate[1] && bcnt == 2'd3);

	// K28.5 when there is nothing to send, and after 255 data symbols
	// in a row so a receiver that slipped finds its place again
	wire enc_is_data = tx_have && (zl_run != 8'd255);
	always @(posedge clk100) begin
		enc_q <= enc8b10b(enc_is_data ? tx_byte[8] : 1'b1,
		                  enc_is_data ? tx_byte[7:0] : 8'hBC, rd);
		enc_data <= enc_is_data;
	end

	always @(posedge clk100) begin
		tx_take <= 1'b0;
		if (f_rst) begin
			txr <= 11'd0;
			tx_have <= 1'b0;
			fpend <= 1'b0;
			fpend2 <= 1'b0;
		end else if (tx_flush) begin
			txr <= txw_f;
			tx_have <= 1'b0;
			fpend <= 1'b0;
			fpend2 <= 1'b0;
		end else begin
			// Keep the next entry in hand. The RAM's address is a
			// register and so is its output: the entry is in tm_q two
			// clocks after the read is asked for.
			fpend2 <= fpend;
			if (fpend2) begin
				tx_byte <= tm_q;
				tx_have <= 1'b1;
			end
			if (fpend) begin
				fpend <= 1'b0;
			end else if (!tx_have && !fpend2 && tx_avail) begin
				tm_ra <= txr[9:0];
				txr <= txr + 11'd1;
				fpend <= 1'b1;
			end
			if (tx_take) tx_have <= 1'b0;
		end
		txr_g <= txr ^ (txr >> 1);

		if (dp_rst) begin
			txsh <= 10'h3FF;
			txleft <= 4'd0;
			bcnt <= 2'd0;
			rd <= 1'b0;
			zl_run <= 8'd0;
			txb <= 1'b0;
			oe1 <= 1'b0;
			oe2 <= 1'b0;
		end else begin
			oe1 <= (f_txsel == 2'd1);
			oe2 <= (f_txsel == 2'd2) && (TX_DS2 != 0);
			bcnt <= bcnt + 2'd1;
			if (bit_end) begin
				bcnt <= 2'd0;
				if (txleft > 4'd1) begin
					txsh <= { 1'b0, txsh[9:1] };
					txleft <= txleft - 4'd1;
					txb <= txsh[1] ^ f_txinv;
				end else begin
					txsh <= enc_q[9:0];
					rd <= enc_q[10];
					txleft <= 4'd10;
					txb <= enc_q[0] ^ f_txinv;
					if (enc_data) begin
						tx_take <= 1'b1;
						zl_run <= zl_run + 8'd1;
					end else
						zl_run <= 8'd0;
				end
			end
		end
	end

	// a flush must not be undone by a fetch in flight: the fetch above is
	// cancelled by tx_flush, and tx_take after a flush finds tx_have clear

endmodule
